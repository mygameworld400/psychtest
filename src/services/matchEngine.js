// MATCH 전용 — ME에서 이미 계산된 69개 차원 점수만으로 "나에게 맞는 상대"를
// 설명한다. 새 질문은 없다. NOW/AFTER처럼 조건 배열을 매칭해 정해진 문장을
// 고르는 규칙엔진이고, AI는 여기 없는 새 문장을 만들지 않는다.

function pick(rules, scores, fallback) {
  for (const rule of rules) {
    if (rule.match(scores)) return rule.text
  }
  return fallback
}

