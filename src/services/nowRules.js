// 마스터 스펙 8장 NOW 해석 규칙. 점수는 scoringEngine이 계산하고, 여기서는
// 정해진 조건에 맞을 때만 핵심 문장을 하나 골라 보여준다 — AI가 임의로 문장을
// 만들지 않는다.
const RULES = [
  {
    id: 'rest_not_breakup',
    match: (s) =>
      (s['관계에너지방전'] ?? 0) >= 75 &&
      (s['혼자회복욕구'] ?? 0) >= 70 &&
      (s['애정잔존'] ?? 0) >= 60 &&
      (s['관계종료의사'] ?? 100) <= 40,
    text: '현재는 관계를 끝내고 싶은 마음보다 관계에서 잠시 벗어나 회복하고 싶은 욕구가 더 강하게 나타납니다.',
  },
  {
    id: 'trust_not_affection',
    match: (s) => (s['신뢰손상'] ?? 0) >= 70 && (s['애정잔존'] ?? 0) >= 60 && (s['상대말불신'] ?? 0) >= 65,
    text: '애정 자체가 크게 사라졌다기보다, 반복된 사건으로 인해 상대의 말과 행동을 믿기 어려워진 점이 현재 관계의 중심 문제에 가깝습니다.',
  },
  {
    id: 'helplessness_not_boredom',
    match: (s) =>
      (s['설렘잔존'] ?? 100) <= 40 &&
      (s['관계무기력'] ?? 0) >= 70 &&
      (s['미해결갈등'] ?? 0) >= 65 &&
      (s['관계회복의지'] ?? 0) >= 55,
    text: "단순한 권태보다 '해도 달라지지 않을 것 같다'는 관계 무기력이 더 크게 나타납니다.",
  },
]

/** scores: { [dimension]: number } -> 매칭된 핵심 문장 배열 (0개일 수도 있음) */
export function matchNowRules(scores) {
  return RULES.filter((r) => r.match(scores)).map((r) => r.text)
}
